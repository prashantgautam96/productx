        # Pattern: \textbf{Role} \\ Company \hfill Duration \begin{itemize}...\end{itemize}
        # Or: \textbf{Role} \\ Company \hfill Duration (without itemize)
        
        # Find all \textbf{} positions
        textbf_matches = list(re.finditer(r'\\textbf\{([^}]+)\}', exp_text))
        
        print(f"[PARSER DEBUG] Found {len(textbf_matches)} \\textbf{{}} matches in experience section")
