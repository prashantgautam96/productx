        # Process each \textbf{} entry
        for idx, match in enumerate(textbf_matches):
            role = self._clean_latex(match.group(1)).strip()
            
            # Get text after this \textbf{} until next \textbf{} or end
            start_pos = match.end()
            if idx + 1 < len(textbf_matches):
                end_pos = textbf_matches[idx + 1].start()
            else:
                end_pos = len(exp_text)
            
            entry_text = exp_text[start_pos:end_pos].strip()
            
            # Extract company and duration
            # Pattern: \\ Company, Location \hfill Duration
            # Or: \\ Company \hfill Duration
            # Or: Company, Location \hfill Duration (without \\)
            company_duration_match = re.search(r'(?:\\\\\s*)?([^\\]+?)\s+\\hfill\s+([^\\\\]+)', entry_text)
            if company_duration_match:
                company_line = self._clean_latex(company_duration_match.group(1)).strip()
                duration = self._clean_latex(company_duration_match.group(2)).strip()
                
                # Extract company name (before comma if location present)
                if ',' in company_line:
                    company = company_line.split(',')[0].strip()
                else:
                    company = company_line
            else:
                # Fallback: look for company pattern without \hfill
                # Pattern: \\ Company, Location -- Duration
                company_match = re.search(r'(?:\\\\\s*)?([A-Z][^\\]+?)(?:,\s*[A-Z][^\\]*)?\s+--\s+([^\\\\]+)', entry_text)
                if company_match:
                    company_line = self._clean_latex(company_match.group(1)).strip()
                    duration = self._clean_latex(company_match.group(2)).strip()
                    if ',' in company_line:
                        company = company_line.split(',')[0].strip()
                    else:
                        company = company_line
                else:
                    # Last fallback: just find company name
                    company_match = re.search(r'(?:\\\\\s*)?([A-Z][a-zA-Z\s&]+?)(?:,\s*[A-Z]|\s+--|\Z)', entry_text)
                    company = self._clean_latex(company_match.group(1)).strip() if company_match else ""
                    duration_match = re.search(r'--\s*([^\\\\]+)', entry_text)
                    duration = self._clean_latex(duration_match.group(1)).strip() if duration_match else ""
            
            # Extract bullets - be more flexible with itemize environment
            bullets = []
            # Look for itemize blocks
            itemize_blocks = re.findall(r'\\begin\{itemize\}(.*?)\\end\{itemize\}', entry_text, re.DOTALL)
            for block in itemize_blocks:
                bullet_matches = re.findall(r'\\item\s+(.+?)(?=\\item|\\end|$)', block, re.DOTALL)
                for bullet_text in bullet_matches:
                    bullet_text = self._clean_latex(bullet_text).strip()
